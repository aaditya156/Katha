from typing import Literal
from pydantic import BaseModel, ConfigDict, Field


class CharacterAppearance(BaseModel):
    model_config = ConfigDict(strict=True)

    name: str = Field(..., description="Character name")
    role: str = Field(..., description="Narrative role (e.g., protagonist, antagonist, supporting, narrator)")
    vocal_archetype: str = Field(..., description="Suggested vocal texture/archetype (e.g., warm baritone, anxious young female)")
    emotional_state: str = Field(..., description="Primary psychological or emotional state in this episode")


class DramaticBeat(BaseModel):
    model_config = ConfigDict(strict=True)

    beat_number: int = Field(..., ge=1)
    description: str = Field(..., description="Core narrative action or dialogue revelation")
    conflict_type: str = Field(..., description="Nature of conflict (e.g., interpersonal, internal, environmental)")
    stakes: str = Field(..., description="What is gained or lost in this beat")


class SceneOutline(BaseModel):
    model_config = ConfigDict(strict=True)

    scene_number: int = Field(..., ge=1)
    heading: str = Field(..., description="Audio scene heading (e.g., INT. OLD DELHI BALCONY - RAIN)")
    atmosphere_soundscape: str = Field(..., description="Acoustic background bed and sound effects cues")
    characters_present: list[str] = Field(..., min_length=1)
    dramatic_objective: str = Field(..., description="What the scene must achieve narratively")
    beats: list[DramaticBeat] = Field(..., min_length=1)


class EpisodeOutline(BaseModel):
    """Structured outline generated by the Planner Agent."""

    model_config = ConfigDict(strict=True)

    title: str = Field(..., description="Catchy episodic title")
    logline: str = Field(..., description="1-2 sentence dramatic summary of the episode")
    target_language: str = Field(..., description="Primary language: hindi, hinglish, or english")
    estimated_duration_minutes: int = Field(..., ge=1, le=30)
    characters: list[CharacterAppearance] = Field(..., min_length=1)
    scenes: list[SceneOutline] = Field(..., min_length=1)
    cliffhanger_or_resolution: str = Field(..., description="The ending hook or emotional resolution of the episode")


class GenerateOutlineRequest(BaseModel):
    model_config = ConfigDict(strict=True)

    series_id: str | None = None
    episode_number: int = Field(default=1, ge=1)
    premise: str = Field(..., min_length=10, max_length=2000, description="Premise or seed concept for the episode")
    target_language: Literal["hindi", "hinglish", "english"] = "hindi"
    target_duration_minutes: int = Field(default=5, ge=1, le=30)
    genre: str = Field(default="drama", max_length=100)
    characters_hint: list[str] | None = None

